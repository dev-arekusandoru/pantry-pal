// openapi.json -> src/api/schema.d.ts
//
// The server documents routes under /api/v1/*; the client uses baseUrl
// "/api/v1", so paths are generated without that prefix (`/pantry`, not
// `/api/v1/pantry`). The un-prefixed root `/health` is dropped because it would
// collide with `/api/v1/health` once stripped.
import openapiTS, { astToString } from "openapi-typescript";
import { readFileSync, writeFileSync } from "node:fs";

const PREFIX = "/api/v1";
const doc = JSON.parse(readFileSync(new URL("../openapi.json", import.meta.url), "utf8"));

const paths = {};
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  if (path.startsWith(`${PREFIX}/`)) paths[path.slice(PREFIX.length)] = item;
}
doc.paths = paths;

const ast = await openapiTS(doc);
const out = new URL("../src/api/schema.d.ts", import.meta.url);
writeFileSync(
  out,
  `/**\n * This file was auto-generated by openapi-typescript (scripts/generate-types.mjs).\n * Do not make direct changes to the file. Regenerate with \`pnpm openapi\`.\n */\n\n${astToString(ast)}`,
);
console.log(`Wrote ${out.pathname}`);
